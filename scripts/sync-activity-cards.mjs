import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const directory = new URL('public/images/activity-cards/', root);
const worklists = new URL('output/missing-images/', root);
const output = new URL('src/data/activity-cards.js', root);

mkdirSync(directory, { recursive: true });
const files = readdirSync(directory).filter((file) => /^m\d+-s\d+-a\d+\.webp$/.test(file)).sort();
const entries = files.map((file) => `  "${file.slice(0, -5)}": "images/activity-cards/${file}",`);
writeFileSync(output, [
  '// Generated by scripts/sync-activity-cards.mjs from public/images/activity-cards/*.webp.',
  'export const ACTIVITY_CARDS = {',
  ...entries,
  '};',
  '',
].join('\n'));

console.log(`${files.length} vignette(s) indexée(s)`);
const missingByLevel = new Map();
for (const list of readdirSync(worklists).filter((file) => /^activity-cards-.*\.jsonl$/.test(file)).sort()) {
  const rows = readFileSync(new URL(list, worklists), 'utf8').split(/\r?\n/).filter((line) => line.trim());
  for (const row of rows) {
    const { file, level } = JSON.parse(row);
    const missing = existsSync(new URL(file, root)) ? 0 : 1;
    missingByLevel.set(level, (missingByLevel.get(level) ?? 0) + missing);
  }
}
for (const [level, count] of missingByLevel) {
  console.log(`${level} : ${count} vignette(s) manquante(s)`);
}
