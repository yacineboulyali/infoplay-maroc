// Publish only reviewed assets. Full resolution source PNGs stay in output/.
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
import { ACTIVITIES } from '../src/data/index.js';

const folder = resolve('output/student-illustrations');
const manifest = JSON.parse(readFileSync(resolve(folder, 'manifest.json'), 'utf8'));
const fields = { match: 'pairs', sort: 'items', order: 'steps', fill: 'lines', quiz: 'qs', hot: 'prompts', asm: 'parts', net: 'devices', robot: 'levels', prog: 'tasks', sim: 'tasks' };
const activities = new Map(ACTIVITIES.map(a => [a.id, a]));
const approved = manifest.questions.filter(q => q.readyForIntegration && q.status === 'generated-reviewed' && !q.generation.needsRegeneration);
const destination = resolve('public/images/student-illustrations');
mkdirSync(destination, { recursive: true });
const index = {}, entries = [], hashes = new Set();
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  for (const q of approved) {
    const activity = activities.get(q.activityId);
    const match = q.dataPath.match(/^data\.([a-z]+)\[(\d+)\]$/);
    if (!activity || !match || match[1] !== fields[activity.type] || !activity.data[match[1]][Number(match[2])]) throw Error(`Invalid source: ${q.id}`);
    const source = resolve(folder, q.asset);
    if (!source.startsWith(folder + '/') && !source.startsWith(folder + '\\')) throw Error('Asset outside package');
    const png = readFileSync(source);
    const hash = createHash('sha256').update(png).digest('hex');
    if (hash !== q.generation.sha256 || hashes.has(hash)) throw Error(`Invalid or repeated asset: ${q.id}`);
    hashes.add(hash);
    const webp = await page.evaluate(async base64 => {
      const image = new Image(); image.src = `data:image/png;base64,${base64}`; await image.decode();
      const canvas = document.createElement('canvas'); canvas.width = canvas.height = 512;
      const context = canvas.getContext('2d'); context.fillStyle = '#fffaf0'; context.fillRect(0, 0, 512, 512);
      const scale = Math.min(512 / image.width, 512 / image.height);
      const width = image.width * scale, height = image.height * scale;
      context.drawImage(image, (512 - width) / 2, (512 - height) / 2, width, height);
      return canvas.toDataURL('image/webp', .88).split(',')[1];
    }, png.toString('base64'));
    const filename = `${q.id}-${hash.slice(0, 10)}.webp`;
    writeFileSync(resolve(destination, filename), Buffer.from(webp, 'base64'));
    const src = `images/student-illustrations/${filename}`;
    index[q.id] = src;
    entries.push({ id: q.id, activityId: q.activityId, dataPath: q.dataPath, sourceAsset: q.asset, src, bytes: statSync(resolve(destination, filename)).size });
  }
} finally { await browser.close(); }
writeFileSync('src/data/student-illustrations.js', '// Generated by scripts/sync-student-illustrations.mjs; reviewed images only.\nexport const STUDENT_ILLUSTRATIONS = ' + JSON.stringify(index, null, 2) + ';\n');
writeFileSync(resolve(folder, 'integration-report.json'), JSON.stringify({ generationPaused: true, generated: manifest.generatedAssets.length, integrated: entries.length, excluded: manifest.generatedAssets.length - entries.length, totalBytes: entries.reduce((n, e) => n + e.bytes, 0), entries }, null, 2) + '\n');
console.log(JSON.stringify({ integrated: entries.length, totalBytes: entries.reduce((n, e) => n + e.bytes, 0), activities: new Set(entries.map(e => e.activityId)).size }));
